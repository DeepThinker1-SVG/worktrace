export const defaultAppPreferences: AppPreferences = { locale: 'zh-CN' };

export function isAppLocale(value: unknown): value is AppLocale {
  return value === 'zh-CN' || value === 'en';
}

export function translate(locale: AppLocale, key: TranslationKey, variables: TranslationVariables = {}): string {
  let template: string = (locale === 'en' ? en : zhCN)[key];

  if (locale === 'en' && variables.count === 1 && enSingular[key]) {
    template = enSingular[key];
  }

  if (locale === 'en' && key === 'workflow.applyConfirm' && variables.createCount === 1) {
    template = 'Apply the AI coding workflow to the current repository? This will create {createCount} file{overwriteText}.';
  }

  if (locale === 'en' && key === 'workflow.bundledApplyConfirm' && variables.createCount === 1) {
    template = 'Import “{name}” ({language}) into the current repository? This will create {createCount} file{overwriteText}.';
  }

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : match,
  );
}
